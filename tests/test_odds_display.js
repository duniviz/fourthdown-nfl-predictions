const assert=require('node:assert/strict');
const fs=require('node:fs');
const api=require('../assets/fd-betting-board.js');
const forecast={home:'BAL',away:'LAC',projected_home_score:24,projected_away_score:20};
const quote={home_spread:-3.5,home_spread_price:-110,away_spread_price:-105,total:46,over_price:105,under_price:-125,home_moneyline_price:-180,away_moneyline_price:155};
const rows=api.gameEdgeRows(forecast,quote,{});
assert.equal(rows.find(x=>x.kind==='Spread').odds,'-110');
assert.equal(rows.find(x=>x.kind==='Total').odds,'-125');
assert.equal(rows.find(x=>x.kind==='Winner').odds,'-180');
assert.match(api.table(rows,10),/DraftKings -125/);
assert.ok(api.gameEdgeRows(forecast,{home_spread:-3.5,total:46},{}).every(x=>x.odds===null));
const player=[{player:'Derrick Henry',team:'BAL',market:'Rushing yards',projection:69.1}];
const line={player:'Derrick Henry',market_key:'player_rushing_yards',line:80.5,under_price:-115,home_team:'Baltimore Ravens',away_team:'Los Angeles Chargers'};
assert.equal(api.propEdgeRows(player,[line])[0].odds,'-115');
assert.equal(api.propEdgeRows(player,[{...line,under_price:undefined}])[0].odds,null);
const board=fs.readFileSync('assets/fd-betting-board.js','utf8');
assert.match(board,/data-home-team=/);
const compact=fs.readFileSync('assets/fd-compact-desk.js','utf8');
assert.match(compact,/attachSlateCards/);
assert.match(compact,/replaceChildren\(card\)/);
const html=fs.readFileSync('index.html','utf8');
assert.match(html,/document\.addEventListener\('click',fdHandleMatchupClick\)/);
assert.match(html,/document\.addEventListener\('toggle',e=>/);
assert.match(fs.readFileSync('assets/fd-betting-board.css','utf8'),/fd-bb-odds/);
console.log('Odds and inline matchup checks passed');
