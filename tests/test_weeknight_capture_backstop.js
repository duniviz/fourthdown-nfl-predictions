const assert = require('assert');
const {decide} = require('../scripts/weeknight_capture_backstop');
const game = {game_id:'2026_11_IND_HOU',kickoff_utc:'2026-11-20T01:15:00Z'};
const time = s => Date.parse(s);
const key = '2026-11-20T01:15:00+00:00';
const done = {refreshes:{[key]:{game_odds:{status:'request_completed'},player_props:{status:'request_completed'}}}};
const lock = [{game_id:game.game_id,kickoff_utc:game.kickoff_utc,lock_status:'last_available'}];
assert.equal(decide(time('2026-11-20T00:31:00Z'),[game],{},[],[]).action,'dispatch');
assert.equal(decide(time('2026-11-20T00:52:00Z'),[game],done,lock,[]).action,'none');
assert.equal(decide(time('2026-11-20T00:52:00Z'),[game],done,[],[]).action,'dispatch');
assert.equal(decide(time('2026-11-20T00:52:00Z'),[game],{},[],[{status:'in_progress',created_at:'2026-11-20T00:50:00Z'}]).action,'wait');
assert.equal(decide(time('2026-11-20T01:12:00Z'),[game],{},[],[]).action,'none');
assert.equal(decide(time('2026-11-20T01:16:00Z'),[game],{},[],[]).action,'none');
const monday = {game_id:'monday',kickoff_utc:'2026-11-24T01:15:00Z'};
assert.equal(decide(time('2026-11-24T00:35:00Z'),[monday],{},[],[]).action,'dispatch');
const summerMonday = {game_id:'summer',kickoff_utc:'2026-09-08T00:15:00Z'};
assert.equal(decide(time('2026-09-07T23:35:00Z'),[summerMonday],{},[],[]).action,'dispatch');
const sunday = {game_id:'sunday',kickoff_utc:'2026-11-23T01:15:00Z'};
assert.equal(decide(time('2026-11-23T00:35:00Z'),[sunday],{},[],[]).action,'none');
assert.throws(()=>decide(Date.now(),[],{},[],[]));
console.log('Weeknight backstop policy passed');
